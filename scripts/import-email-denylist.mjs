#!/usr/bin/env node
// Writes a migration that loads the full work-email denylist (AUTH-04).
//
//   node scripts/import-email-denylist.mjs <path-to-list> [more files…]
//
// Each file can be the mintly-web source (for example
// amplify/backend/function/mintlywebPreSignup/src/email-filter-denylist.js),
// a JSON array or a plain list with one domain per line: every quoted string
// or line that looks like a domain is taken. The new migration goes in
// supabase/migrations; apply it with `npm run db:push`.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const files = process.argv.slice(2);
if (files.length === 0) {
  console.error("Usage: node scripts/import-email-denylist.mjs <path-to-list> [more files…]");
  process.exit(1);
}

const domainPattern = /^(?=.{3,253}$)(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$/;
const domains = new Set();

for (const file of files) {
  const text = readFileSync(file, "utf8");
  const candidates = [
    ...[...text.matchAll(/["'`]([^"'`\s]+)["'`]/g)].map((match) => match[1]),
    ...text.split(/\r?\n/),
  ];
  for (const candidate of candidates) {
    const domain = candidate.trim().toLowerCase().replace(/^@/, "").replace(/\.$/, "");
    if (domainPattern.test(domain)) domains.add(domain);
  }
}

if (domains.size === 0) {
  console.error("No domains found.");
  process.exit(1);
}

const sorted = [...domains].sort();
const rows = [];
for (let i = 0; i < sorted.length; i += 5) {
  rows.push(
    "  " +
      sorted
        .slice(i, i + 5)
        .map((domain) => `('${domain}')`)
        .join(", "),
  );
}

const stamp = new Date()
  .toISOString()
  .replace(/[-:TZ]/g, "")
  .slice(0, 14);
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const path = join(root, "supabase", "migrations", `${stamp}_email_domain_denylist.sql`);

writeFileSync(
  path,
  [
    "-- AUTH-04: the full work-email denylist, generated by scripts/import-email-denylist.mjs.",
    `-- ${sorted.length} domains. Re-running the script adds new domains; it never removes any.`,
    "insert into public.email_domain_denylist (domain) values",
    rows.join(",\n"),
    "on conflict do nothing;",
    "",
  ].join("\n"),
);

console.log(`Wrote ${sorted.length} domains to ${path}`);
